"""Reproducible C8 qualification profile, independent of a dirty checkout's HEAD.

Run with the Python environment whose dependencies should be measured. Commits
are created only in new isolated copies under --output, never in --repository.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import math
import os
from pathlib import Path
import platform
import shutil
import sqlite3
import statistics
import subprocess
import sys
import time


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def manifest(root):
    return {p.relative_to(root).as_posix(): sha256(p) for p in sorted(root.rglob("*"))
            if p.is_file() and ".git" not in p.relative_to(root).parts
            and "__pycache__" not in p.parts and p.suffix != ".pyc"}


def git(root, *args):
    return subprocess.check_output(["git", "-c", "core.hooksPath=" + os.devnull,
                                    "-C", str(root), *args], text=True, stderr=subprocess.PIPE).strip()


def pin(root, label):
    """Pin newly generated bytes; reject accidental use on an existing checkout."""
    if (root / ".git").exists():
        raise ValueError("Refusing to commit into an existing checkout")
    git(root, "init", "-q")
    git(root, "config", "core.autocrlf", "false")
    git(root, "add", "--all")
    git(root, "-c", "user.name=SpecGraph qualification fixture",
        "-c", "user.email=qualification@invalid.local", "-c", "commit.gpgsign=false",
        "commit", "--no-verify", "-qm", label)
    return {"commit": git(root, "rev-parse", "HEAD"), "tree": git(root, "rev-parse", "HEAD^{tree}"),
            "status": git(root, "status", "--porcelain"), "authority": "isolated_generated_copy"}


def generate_corpus(root, modules=100, functions=20):
    root.mkdir(parents=True, exist_ok=False)
    (root / "src").mkdir()
    (root / "notes").mkdir()
    (root / ".gitattributes").write_text("* -text\n", encoding="utf-8", newline="\n")
    (root / "specgraph.yaml").write_text(
        "project_name: specgraph-c8-reference-v1\nindexed_paths: [src]\n"
        "governed_paths: []\nsearch_paths: [notes]\nstrict_orphan_check: false\n", encoding="utf-8", newline="\n")
    for module in range(modules):
        lines = []
        for function in range(functions):
            name = f"node_{module:04}_{function:04}"
            lines += [f"def {name}(value=0):",
                      f'    """Transformação {module}/{function}: café, 漢字 and bounded evidence."""',
                      f"    result = value + {function}",
                      f"    return node_{module:04}_{function-1:04}(result)" if function else "    return result", ""]
        (root / "src" / f"module_{module:04}.py").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for number in range(20):
        (root / "notes" / f"design_{number:02}.md").write_text(
            f"# Design {number}\nTransactional custody topic_{number:02}.\n" +
            "Published evidence is scoped. Unicode café 漢字 remains intact.\n" * 30, encoding="utf-8", newline="\n")


def summarize(samples):
    if not samples:
        raise ValueError("Cannot summarize an empty sample set")
    durations = sorted(item["wall_ms"] for item in samples)
    percentile = lambda q: durations[math.ceil(q * len(durations)) - 1]
    q1, q3 = percentile(.25), percentile(.75)
    threshold = q3 + 1.5 * (q3 - q1)
    statuses = {}
    for item in samples:
        statuses[item["status"]] = statuses.get(item["status"], 0) + 1
    return {"samples": len(samples), "p50_ms": statistics.median(durations),
            "p95_ms": percentile(.95), "p99_ms": percentile(.99), "max_ms": max(durations),
            "mean_ms": statistics.mean(durations), "statuses": statuses,
            "mean_output_bytes": statistics.mean(item["output_bytes"] for item in samples),
            "outlier_rule": "wall_ms > Q3 + 1.5*IQR; retained in every aggregate",
            "outlier_threshold_ms": threshold,
            "outlier_samples": [item["sample"] for item in samples if item["wall_ms"] > threshold]}


def hardware():
    cpu = platform.processor()
    memory = None
    if Path("/proc/cpuinfo").is_file():
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                cpu = line.split(":", 1)[1].strip()
                break
        memory = next((line for line in Path("/proc/meminfo").read_text().splitlines()
                       if line.startswith("MemTotal:")), None)
    if os.name == "nt":
        import ctypes
        class Memory(ctypes.Structure):
            _fields_ = [("length", ctypes.c_ulong), ("load", ctypes.c_ulong)] + [
                (name, ctypes.c_ulonglong) for name in ("total", "available", "page", "available_page", "virtual", "available_virtual", "extended")]
        info = Memory(); info.length = ctypes.sizeof(info)
        if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(info)):
            memory = info.total
    dependencies = {}
    for package in ("PyYAML", "tree-sitter", "tree-sitter-typescript", "tree-sitter-rust"):
        try:
            dependencies[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            dependencies[package] = "ABSENT"
    return {"platform": platform.platform(), "machine": platform.machine(), "cpu": cpu,
            "logical_cpus": os.cpu_count(), "visible_memory": memory, "python": sys.version,
            "executable": sys.executable, "sqlite": sqlite3.sqlite_version, "dependencies": dependencies}


def run_profile(repository, output, *, samples=100, rounds=2):
    if samples < 100 or rounds < 2:
        raise ValueError("Qualification requires >=100 samples and >=2 rounds per transport")
    output.mkdir(parents=True, exist_ok=False)
    software = output / "software"
    software.mkdir()
    for name in ("pyproject.toml", "README.md", "LICENSE"):
        if (repository / name).is_file():
            shutil.copy2(repository / name, software / name)
    shutil.copytree(repository / "src/specgraph", software / "src/specgraph",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    shutil.copy2(Path(__file__), software / "qualify_benchmark.py")
    (software / ".gitattributes").write_text("* -text\n", encoding="utf-8", newline="\n")
    software_manifest = manifest(software)
    software_pin = pin(software, "C8 exact software bytes for benchmark; not upstream release")
    corpus = output / "corpus"
    generate_corpus(corpus)
    corpus_manifest = manifest(corpus)
    corpus_pin = pin(corpus, "C8 generated reference corpus v1")
    # Import only the copied software. The caller may run this from another cwd.
    if any(name == "specgraph" or name.startswith("specgraph.") for name in sys.modules):
        raise ValueError("Run qualification in a fresh interpreter without pre-imported SpecGraph")
    sys.path.insert(0, str(software / "src"))
    from specgraph.indexer import index_repository
    from specgraph.query import project_query, serialize_query
    from specgraph.storage import index_path
    state = output / "state"
    indexed = index_repository(corpus, state_dir=state)
    cases = [
        {"id": "exact", "query": "node_0050_0010", "mode": "search", "expect": "HIT"},
        {"id": "identity", "query": "src/module_0010.py:node_0010_0005", "mode": "search", "expect": "HIT"},
        {"id": "path", "query": "module_0040.py", "mode": "search", "expect": "HIT"},
        {"id": "broad", "query": "node", "mode": "search", "expect": "HIT"},
        {"id": "document", "query": "transactional", "mode": "search", "expect": "HIT"},
        {"id": "miss", "query": "zzzz_absent_7cf489", "mode": "search", "expect": "NO_MATCH_WITHIN_INDEXED_SCOPE"},
        {"id": "unicode_miss", "query": "inexistente_東京_7cf489", "mode": "search", "expect": "NO_MATCH_WITHIN_INDEXED_SCOPE"},
        {"id": "context", "query": "node_0050_0010", "mode": "context", "expect": "HIT"},
        {"id": "refs", "query": "node_0050_0010", "mode": "refs", "expect": "HIT"},
        {"id": "neighbors", "query": "node_0050_0010", "mode": "neighbors", "expect": "HIT"},
    ]
    env = dict(os.environ, PYTHONPATH=str(software / "src"), PYTHONDONTWRITEBYTECODE="1",
               TARE_SPECGRAPH_STATE_DIR=str(state))
    env.pop("PYTHONHOME", None)
    records, summaries = [], []
    raw = output / "samples.jsonl"
    with raw.open("w", encoding="utf-8", newline="\n") as stream:
        for number in range(rounds):
            # Alternate transport order to disclose/reduce a fixed-order effect.
            for transport in (("sdk", "cli") if number % 2 == 0 else ("cli", "sdk")):
                batch = []
                for i in range(samples):
                    case = cases[i % len(cases)]
                    started = time.perf_counter_ns()
                    if transport == "sdk":
                        response = project_query(corpus, case["query"], mode=case["mode"], state_dir=state)
                        before_serialization = time.perf_counter_ns()
                        wire = serialize_query(response).encode("utf-8")
                        finished = time.perf_counter_ns()
                        serialization_ms = (finished - before_serialization) / 1e6
                    else:
                        command = {"search": "query", "context": "code-context"}.get(case["mode"], case["mode"])
                        completed = subprocess.run([sys.executable, "-m", "specgraph.cli", "--root", str(corpus),
                                                    command, case["query"], "--format", "json"],
                                                   cwd=output, env=env, capture_output=True, timeout=30)
                        finished = time.perf_counter_ns()
                        if completed.returncode not in (0, 1):
                            raise RuntimeError(completed.stderr.decode("utf-8", errors="replace"))
                        wire = completed.stdout
                        response = json.loads(wire)
                        serialization_ms = None  # Included in child wall time, not separately instrumented.
                    snapshot = response.get("content_hash", response.get("snapshot", {}).get("content_hash"))
                    if snapshot != indexed["content_hash"]:
                        raise AssertionError("Benchmark mixed published generations")
                    if case["expect"] == "HIT" and not response.get("results"):
                        raise AssertionError(f"Expected useful results for {case['id']}: {response['status']}")
                    if "miss" in case["id"] and response.get("results"):
                        raise AssertionError("Expected miss produced results")
                    record = {"round": number + 1, "transport": transport, "sample": i + 1,
                              "case": case["id"], "mode": case["mode"], "query": case["query"],
                              "wall_ms": (finished - started) / 1e6, "serialization_ms": serialization_ms,
                              "output_bytes": len(wire), "status": response["status"],
                              "result_count": len(response.get("results", [])), "content_hash": snapshot}
                    stream.write(json.dumps(record, ensure_ascii=False) + "\n")
                    stream.flush()
                    batch.append(record); records.append(record)
                summaries.append({"round": number + 1, "transport": transport, **summarize(batch),
                                  "by_case": {case["id"]: summarize([r for r in batch if r["case"] == case["id"]]) for case in cases}})
    final_manifests = manifest(software), manifest(corpus)
    if final_manifests != (software_manifest, corpus_manifest):
        raise AssertionError("Pinned benchmark input bytes changed during measurement")
    receipt = {"schema": "tare.tools/specgraph-c8-profile/1", "profile": "generated-python-2000-symbols-v1",
               "software": {**software_pin, "root": str(software), "manifest": software_manifest},
               "upstream_checkout": {"root": str(repository), "head": git(repository, "rev-parse", "HEAD"),
                                     "authority": "source of copied bytes; HEAD is not claimed to contain working changes"},
               "corpus": {**corpus_pin, "root": str(corpus), "manifest": corpus_manifest,
                          "config_sha256": sha256(corpus / "specgraph.yaml")},
               "hardware": {**hardware(), "storage_location": str(output),
                            "storage_class": ("WSL Windows-mounted filesystem" if str(output).startswith("/mnt/")
                                              else "native filesystem; physical disk class not asserted")},
               "index": {k: indexed[k] for k in ("content_hash", "revision_seq", "coverage")},
               "state": {"directory": str(state), "sqlite_path": str(index_path(corpus, state_dir=state)),
                         "location_policy": "explicit profile state below output; production native default is a separate policy"},
               "cases": cases, "rounds": summaries, "samples_file": raw.name, "samples_sha256": sha256(raw),
               "total_samples": len(records), "first_sample_included": True,
               "measurement": {"sdk": "SQLite open/read/assemble/serialize/UTF8 encode/close",
                               "cli": "fresh interpreter process through complete UTF8 stdout, including serialization; parent JSON decode excluded"},
               "cache_state": "OS cache uncontrolled; no query prewarm; index creation precedes measurement",
               "excluded_costs": ["index creation", "network", "MCP framing", "agent reasoning", "IDE host reload"],
               "claims": {"profile_executed": True, "release_qualified": False,
                          "token_savings": "NOT_MEASURED", "graphify_superiority": "NOT_MEASURED"}}
    (output / "receipt.json").write_text(json.dumps(receipt, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--samples", type=int, default=100)
    parser.add_argument("--rounds", type=int, default=2)
    arguments = parser.parse_args()
    result = run_profile(arguments.repository.resolve(), arguments.output.resolve(),
                         samples=arguments.samples, rounds=arguments.rounds)
    print(json.dumps({"receipt": str(arguments.output / "receipt.json"), "samples": result["total_samples"]}))
